#include <stdio.h>
#include <math.h>  // Для квадратного кореня sqrt() и модуля fabs()

// Функция вычисления расстояния между двумя точками
double distance(double x1, double y1, double x2, double y2) {
    return sqrt((x2 - x1) * (x2 - x1) + (y2 - y1) * (y2 - y1));
}

int main() {
    double x1, y1, r1, x2, y2, r2;
    
    // Читаем координаты центров и радиусы
    scanf("%lf %lf %lf %lf %lf %lf", &x1, &y1, &r1, &x2, &y2, &r2);
    
    // Расстояние между центрами кругов
    double d = distance(x1, y1, x2, y2);
    
    // Точность для сравнения вещественных чисел
    double eps = 1e-5;
    
    // Возможны три случая:
    // 1. Круги не пересекаются: d > r1 + r2 (расстояние больше суммы радиусов) или d < |r1 - r2| (один круг внутри другого)
    // 2. Круги касаются: d = r1 + r2 (внешнее касание) или d = |r1 - r2| (внутреннее касание)
    // 3. Круги пересекаются: |r1 - r2| < d < r1 + r2
    
    // Проверяем не пересекаются ли круги
    if (d > r1 + r2 || d < fabs(r1 - r2)) {
        printf("не пересекаются\n");
    }
    // Проверяем касаются ли круги (точность eps)
    else if (fabs(d - (r1 + r2)) < eps || fabs(d - fabs(r1 - r2)) < eps) {
        printf("касаются\n");
    }
    // Иначе круги пересекаются
    else {
        printf("пересекаются\n");
    }
    
    return 0;
}